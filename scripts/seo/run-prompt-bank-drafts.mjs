// scripts/seo/run-prompt-bank-drafts.mjs
//
// Modal-runnable producer that consumes a deterministic prompt bank
// (data/seo/random-prompt-bank.jsonl) and produces SEO articles.
//
// Behaviour (matches the Modal AI SEO contract):
//   - Reads each prompt object exactly as it lives in the bank.
//   - Calls the existing AI provider router (ai-router.mjs), which already
//     supports failover across groq, cerebras, cloudflare, gemini, nvidia.
//     The router treats 429s as a signal to skip to the next provider.
//   - Resume support: any promptId already present in
//     dist/seo/generated-drafts.json is skipped on a subsequent run.
//   - Writes each successful article to content/seo-ready/<slug>.md so the
//     existing seo-ready loader (lib/seo-ready-articles.ts) can pick it up.
//   - Writes per-article back-end metadata (provider, model, hashes,
//     generation timestamp) to dist/seo/generated-drafts.json. Public
//     pages must NEVER render those fields.
//
// Critical constraint: native generation only. The ZH prompt asks for
// Chinese, the EN prompt asks for English. We never call a translation API
// and we always record { generationMode: "native", translationApiUsed:
// false, translatedFrom: null }.

import { createHash } from "crypto"
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs"
import { dirname, join } from "path"
import { fileURLToPath } from "url"
import { generateWithRouter, sleep } from "./ai-router.mjs"

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, "../..")

const PROMPT_BANK_FILE = join(ROOT, process.env.PROMPT_BANK_FILE || "data/seo/random-prompt-bank.jsonl")
const OUTPUT_DRAFTS_FILE = join(ROOT, process.env.OUTPUT_DRAFTS_FILE || "dist/seo/generated-drafts.json")
const READY_DIR = join(ROOT, "content/seo-ready")

const BATCH_SIZE = Number.parseInt(process.env.BATCH_SIZE || "10", 10)
const CONCURRENCY = Math.max(1, Number.parseInt(process.env.CONCURRENCY || "2", 10))
const RATE_DELAY_MS = Number.parseInt(process.env.RATE_DELAY_MS || "3000", 10)
const TIMEOUT_MS = Number.parseInt(process.env.TIMEOUT_MS || "60000", 10)
const MAX_TOKENS = Number.parseInt(process.env.MAX_TOKENS || "2500", 10)
const MIN_SCORE = Number.parseInt(process.env.MIN_SCORE || "90", 10)
const ONLY_LOCALE = (process.env.ONLY_LOCALE || "").toLowerCase() // "en" | "zh" | ""
const RUN_LIMIT = Number.parseInt(process.env.RUN_LIMIT || "0", 10) // 0 = no cap

// ---------------------------------------------------------------------------
// Public-facing tech-leak guard. The list mirrors check-public-no-tech-leak.mjs.
// If any of these phrases appear in the model output we mark the draft as
// "needs-review" and refuse to publish it. The article must never reach
// content/seo-ready in that case.
// ---------------------------------------------------------------------------
const BANNED_PHRASES_FOR_BODY = [
  /\bAI provider\b/i,
  /\bGroq\b/i,
  /\bCerebras\b/i,
  /\bCloudflare AI\b/i,
  /\bGemini\b/i,
  /\bNvidia\b/i,
  /\bprompt bank\b/i,
  /\brandom prompt\b/i,
  /\bgenerated by AI\b/i,
  /\broute manifest\b/i,
  /\bbodyHash\b/,
  /\bpromptHash\b/,
  /\bprofileHash\b/,
  /\bJSONL\b/,
  /\bSEO script\b/i,
  /\binternal metadata\b/i,
  /\bautomation pipeline\b/i,
  /\bworker pipeline\b/i,
  /\bcron\b/i,
  /(?<![A-Za-z\u4e00-\u9fff])prompt(?![A-Za-z])/i, // bare "prompt"
  /\bModal\b/, // capital-M Modal as a brand reference (case-sensitive)
  /\bIntro paragraph mentioning\b/i,
  /\bReturn valid JSON\b/i,
  /\bBody requirements\b/i,
  /\bmarkdown skeleton\b/i,
  /\bQQ\b/i,
  /\bwebmaster\b/i,
  /domain\s+for\s+sale/i,
  /advertising\s+cooperation/i,
  /parked\s+domain/i,
  /local\s+contact/i,
  /提示词/,
  /路由清单/,
  /流水线/,
  /定时任务/,
  /内部 ?metadata/i,
  /本站/,
  /联系QQ/i,
  /本地联系/,
  /站长/,
  /广告合作/,
  /域名出售/,
  /开头段落/,
  /正文要求/,
  /只返回合法 JSON/,
]

function detectLeaks(text) {
  if (!text) return []
  const hits = []
  for (const pattern of BANNED_PHRASES_FOR_BODY) {
    if (pattern.test(text)) hits.push(String(pattern))
  }
  return hits
}

// ---------------------------------------------------------------------------
// JSONL prompt bank
// ---------------------------------------------------------------------------

function loadPromptBank() {
  if (!existsSync(PROMPT_BANK_FILE)) {
    console.error(`Missing prompt bank file: ${PROMPT_BANK_FILE}`)
    console.error("Run: pnpm seo:prompt-bank")
    process.exit(1)
  }
  const raw = readFileSync(PROMPT_BANK_FILE, "utf8")
  const out = []
  let lineNo = 0
  for (const line of raw.split(/\r?\n/)) {
    lineNo++
    const trimmed = line.trim()
    if (!trimmed) continue
    try {
      out.push(JSON.parse(trimmed))
    } catch (err) {
      console.error(`Failed to parse prompt bank line ${lineNo}: ${err.message}`)
      process.exit(1)
    }
  }
  if (out.length === 0) {
    console.error("Prompt bank is empty.")
    process.exit(1)
  }
  return out
}

function loadDrafts() {
  if (!existsSync(OUTPUT_DRAFTS_FILE)) return { drafts: [] }
  try {
    const parsed = JSON.parse(readFileSync(OUTPUT_DRAFTS_FILE, "utf8"))
    if (Array.isArray(parsed.drafts)) return parsed
  } catch {
    console.warn("Existing drafts file unreadable; starting fresh.")
  }
  return { drafts: [] }
}

function saveDrafts(state) {
  mkdirSync(dirname(OUTPUT_DRAFTS_FILE), { recursive: true })
  writeFileSync(OUTPUT_DRAFTS_FILE, JSON.stringify(state, null, 2) + "\n", "utf8")
}

function alternatePathFor(route) {
  if (route.startsWith("/en/")) return route.slice(3)
  return `/en${route}`
}

function safeYaml(value = "") {
  return String(value).replaceAll('"', '\\"').replace(/\r?\n/g, " ").trim()
}

function sha256Hex(s) {
  return createHash("sha256").update(s).digest("hex")
}

function canonicalSlugFor(prompt) {
  const short = (prompt.profileHash || "").slice(0, 8) || "x"
  const base = `${prompt.locale}-${prompt.citySlug}-${prompt.topicSlug}-${short}`
  return base.toLowerCase()
}

// ---------------------------------------------------------------------------
// JSON parsing of model output. The prompt asks for a strict JSON object;
// providers occasionally wrap it in code fences or pre-amble text. We try
// hard to recover the JSON before failing.
// ---------------------------------------------------------------------------

function extractJsonObject(text) {
  if (!text) return null
  const trimmed = text.trim()

  // Strip fenced code blocks.
  const fenced = trimmed
    .replace(/^```(?:json)?\s*/i, "")
    .replace(/\s*```$/i, "")
    .trim()

  const candidates = [trimmed, fenced]

  for (const c of candidates) {
    try {
      const parsed = JSON.parse(c)
      if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) return parsed
    } catch {
      // ignore and try harder
    }
  }

  // Try to find the largest balanced { ... } block.
  for (const candidate of candidates) {
    let depth = 0
    let start = -1
    let bestStart = -1
    let bestEnd = -1
    let inStr = false
    let escape = false
    for (let i = 0; i < candidate.length; i++) {
      const ch = candidate[i]
      if (escape) {
        escape = false
        continue
      }
      if (ch === "\\") {
        escape = true
        continue
      }
      if (ch === '"') {
        inStr = !inStr
        continue
      }
      if (inStr) continue
      if (ch === "{") {
        if (depth === 0) start = i
        depth++
      } else if (ch === "}") {
        depth--
        if (depth === 0 && start !== -1) {
          bestStart = start
          bestEnd = i + 1
        }
      }
    }
    if (bestStart !== -1 && bestEnd !== -1) {
      try {
        return JSON.parse(candidate.slice(bestStart, bestEnd))
      } catch {
        // fall through
      }
    }
  }

  return null
}

// ---------------------------------------------------------------------------
// Quality scoring. We deliberately keep this lightweight: hard rule violations
// (wrong locale, leaked tech terms, missing fields) score 0 and are never
// promoted. Soft signals (length, FAQ presence) bump the score upwards.
// ---------------------------------------------------------------------------

function isMostlyChinese(s) {
  const total = s.length
  if (total === 0) return false
  const chinese = (s.match(/[\u4e00-\u9fff]/g) || []).length
  return chinese / total > 0.3
}

function isMostlyEnglish(s) {
  const total = s.length
  if (total === 0) return false
  const ascii = (s.match(/[A-Za-z]/g) || []).length
  return ascii / total > 0.4
}

function looksLikeJsonWrapper(text = "") {
  const s = String(text || "").trim()
  if (!s) return false
  if (/^\{[\s\S]*"title"\s*:/i.test(s)) return true
  if (/^\{[\s\S]*"body"\s*:/i.test(s)) return true
  if (/"(?:title|description|body|locale|slug)"\s*:/i.test(s.slice(0, 900))) return true
  return false
}

function duplicateMarkdownHeadings(body, level = 2) {
  const marker = "#".repeat(level)
  const headings = [...String(body).matchAll(new RegExp(`^${marker}\\s+(.+)$`, "gm"))]
    .map((m) => m[1].trim().toLowerCase())
    .filter(Boolean)
  return headings.length - new Set(headings).size
}

function scoreArticle(prompt, parsed) {
  const issues = []
  if (!parsed) return { score: 0, issues: ["json-parse-failed"] }
  if (!parsed.title) issues.push("missing-title")
  if (!parsed.body) issues.push("missing-body")
  if (!parsed.description) issues.push("missing-description")
  if (parsed.locale && parsed.locale !== prompt.locale) issues.push("locale-mismatch")

  const body = String(parsed.body || "")
  const title = String(parsed.title || "")
  const description = String(parsed.description || "")
  const haystack = `${title}\n${description}\n${body}`

  const leakHits = detectLeaks(haystack)
  if (leakHits.length) issues.push(`tech-leak:${leakHits.length}`)
  if (looksLikeJsonWrapper(haystack) || looksLikeJsonWrapper(body) || looksLikeJsonWrapper(description)) {
    issues.push("json-wrapper-in-public-text")
  }

  if (prompt.locale === "zh" && !isMostlyChinese(body)) issues.push("body-not-chinese")
  if (prompt.locale === "en" && !isMostlyEnglish(body)) issues.push("body-not-english")

  const minLen = prompt.locale === "en" ? 1500 : 900
  if (body.length < minLen) issues.push(`body-too-short:${body.length}`)
  const paragraphCount = String(body)
    .split(/\n{2,}/)
    .map((part) => part.trim())
    .filter((part) => part && !part.startsWith("#") && !/^[-*]\s+/m.test(part))
    .length
  if (paragraphCount < 10) issues.push(`too-few-paragraphs:${paragraphCount}`)
  const duplicateH2 = duplicateMarkdownHeadings(body, 2)
  if (duplicateH2 > 0) issues.push(`duplicate-h2:${duplicateH2}`)

  if (issues.length === 0) return { score: 100, issues }
  if (issues.some((s) => s.startsWith("tech-leak") || s === "json-wrapper-in-public-text" || s.startsWith("duplicate-h2") || s.startsWith("too-few-paragraphs") || s === "locale-mismatch" || s === "body-not-chinese" || s === "body-not-english" || s === "json-parse-failed")) {
    return { score: 0, issues }
  }
  // soft penalties
  let score = 100
  if (issues.find((x) => x.startsWith("body-too-short"))) score -= 12
  if (issues.includes("missing-description")) score -= 8
  if (issues.includes("missing-title")) score -= 30
  return { score: Math.max(score, 0), issues }
}

// ---------------------------------------------------------------------------
// Worker: run a single prompt
// ---------------------------------------------------------------------------

async function runOne(prompt) {
  const started = Date.now()
  const generation = await generateWithRouter({
    prompt: prompt.userPrompt,
    system: prompt.systemInstruction,
    maxTokens: MAX_TOKENS,
    timeoutMs: TIMEOUT_MS,
  })
  const elapsed = Date.now() - started

  const parsed = extractJsonObject(generation.content)
  const { score, issues } = scoreArticle(prompt, parsed)

  const body = String(parsed?.body || "").trim()
  const title = String(parsed?.title || "").trim()
  const description = String(parsed?.description || "").trim()
  const modelSlugRaw = String(parsed?.slug || "").trim().toLowerCase()
  const slug = modelSlugRaw && /^[a-z0-9][a-z0-9-]{2,80}$/.test(modelSlugRaw)
    ? modelSlugRaw
    : canonicalSlugFor(prompt)

  const status = score >= MIN_SCORE && issues.length === 0 ? "ready" : "needs-review"

  return {
    prompt,
    generation,
    parsed,
    score,
    issues,
    title,
    description,
    body,
    slug,
    status,
    elapsedMs: elapsed,
  }
}

// ---------------------------------------------------------------------------
// File output. The .md frontmatter intentionally avoids any of the banned
// public-facing tech terms while still providing the keys that the existing
// seo-ready loader (lib/seo-ready-articles.ts) understands.
// ---------------------------------------------------------------------------

function articleMarkdown(prompt, result) {
  const canonicalPath = prompt.route
  const alternatePath = alternatePathFor(prompt.route)
  const translationKey = result.slug.replace(/^en-/, "")

  const front = [
    "---",
    `slug: "${safeYaml(result.slug)}"`,
    `canonicalPath: "${safeYaml(canonicalPath)}"`,
    `alternatePath: "${safeYaml(alternatePath)}"`,
    `translationKey: "${safeYaml(translationKey)}"`,
    `lang: "${prompt.locale}"`,
    `title: "${safeYaml(result.title)}"`,
    prompt.locale === "zh" ? `titleZh: "${safeYaml(result.title)}"` : "",
    `description: "${safeYaml(result.description)}"`,
    `pageType: "city-topic"`,
    `aiQualityScore: ${result.score}`,
    `status: "${result.status}"`,
    "---",
    "",
  ].filter(Boolean).join("\n")

  return `${front}${result.body.trim()}\n`
}

function writeReadyArticle(prompt, result) {
  if (result.status !== "ready") return null
  mkdirSync(READY_DIR, { recursive: true })
  const file = join(READY_DIR, `${result.slug}.md`)
  writeFileSync(file, articleMarkdown(prompt, result), "utf8")
  return file
}

// ---------------------------------------------------------------------------
// Main loop
// ---------------------------------------------------------------------------

async function main() {
  const bank = loadPromptBank()
  const state = loadDrafts()
  const completed = new Set(state.drafts.map((d) => d.promptId).filter(Boolean))

  const filtered = bank.filter((p) => {
    if (ONLY_LOCALE && p.locale !== ONLY_LOCALE) return false
    return true
  })

  let queue = filtered.filter((p) => !completed.has(p.promptId))
  if (RUN_LIMIT > 0) queue = queue.slice(0, RUN_LIMIT)

  console.log(`Prompt bank      : ${PROMPT_BANK_FILE}`)
  console.log(`Drafts file      : ${OUTPUT_DRAFTS_FILE}`)
  console.log(`Total prompts    : ${bank.length}`)
  console.log(`Already done     : ${state.drafts.length}`)
  console.log(`Locale filter    : ${ONLY_LOCALE || "(none)"}`)
  console.log(`To process       : ${queue.length}`)
  console.log(`Concurrency      : ${CONCURRENCY}`)
  console.log(`Batch size       : ${BATCH_SIZE}`)
  console.log(`Rate delay (ms)  : ${RATE_DELAY_MS}`)
  console.log(`Timeout (ms)     : ${TIMEOUT_MS}`)

  if (queue.length === 0) {
    console.log("Nothing to do. Exiting.")
    return
  }

  let success = 0
  let failed = 0
  let needsReview = 0
  let processedSinceCheckpoint = 0

  for (let offset = 0; offset < queue.length; offset += CONCURRENCY) {
    const chunk = queue.slice(offset, offset + CONCURRENCY)
    const results = await Promise.allSettled(chunk.map((p) => runOne(p)))

    for (let i = 0; i < chunk.length; i++) {
      const prompt = chunk[i]
      const r = results[i]

      if (r.status === "rejected") {
        failed++
        state.drafts.push({
          promptId: prompt.promptId,
          seed: prompt.seed,
          locale: prompt.locale,
          citySlug: prompt.citySlug,
          cityNameLocalized: prompt.cityNameLocalized,
          topicSlug: prompt.topicSlug,
          topicNameLocalized: prompt.topicNameLocalized,
          route: prompt.route,
          routeExistsInManifest: true,
          selectedAngle: prompt.angle?.id,
          selectedStructure: prompt.structure,
          selectedOpeningStyle: prompt.openingStyle,
          selectedFaqMode: prompt.faqMode,
          selectedCtaPosition: prompt.ctaPosition,
          selectedExampleType: prompt.exampleType,
          selectedTone: prompt.tone,
          promptHash: prompt.promptHash,
          profileHash: prompt.profileHash,
          generationMode: "native",
          translationApiUsed: false,
          translatedFrom: null,
          status: "failed",
          error: r.reason?.message?.slice(0, 1500) || String(r.reason),
          generatedAt: new Date().toISOString(),
        })
        console.log(`[FAIL] ${prompt.promptId} ${prompt.route} : ${r.reason?.message?.slice(0, 200) || r.reason}`)
        continue
      }

      const result = r.value
      const writtenFile = writeReadyArticle(prompt, result)

      const draftEntry = {
        promptId: prompt.promptId,
        seed: prompt.seed,
        locale: prompt.locale,
        citySlug: prompt.citySlug,
        cityNameLocalized: prompt.cityNameLocalized,
        topicSlug: prompt.topicSlug,
        topicNameLocalized: prompt.topicNameLocalized,
        route: prompt.route,
        routeExistsInManifest: true,
        selectedAngle: prompt.angle?.id,
        selectedStructure: prompt.structure,
        selectedOpeningStyle: prompt.openingStyle,
        selectedFaqMode: prompt.faqMode,
        selectedCtaPosition: prompt.ctaPosition,
        selectedExampleType: prompt.exampleType,
        selectedTone: prompt.tone,
        promptHash: prompt.promptHash,
        profileHash: prompt.profileHash,
        title: result.title,
        description: result.description,
        bodyHash: sha256Hex(result.body || ""),
        structureHash: sha256Hex(`${prompt.structure}|${prompt.openingStyle}|${prompt.faqMode}|${prompt.ctaPosition}|${prompt.titlePattern}`),
        generationMode: "native",
        translationApiUsed: false,
        translatedFrom: null,
        provider: result.generation.provider,
        model: result.generation.model || null,
        status: result.status,
        score: result.score,
        issues: result.issues,
        slug: result.slug,
        outputFile: writtenFile ? writtenFile.replace(`${ROOT}/`, "") : null,
        elapsedMs: result.elapsedMs,
        generatedAt: new Date().toISOString(),
      }

      state.drafts.push(draftEntry)
      if (result.status === "ready") {
        success++
        console.log(`[OK]   ${prompt.promptId} ${prompt.route} via ${result.generation.provider} (score ${result.score})`)
      } else {
        needsReview++
        console.log(`[REVW] ${prompt.promptId} ${prompt.route} via ${result.generation.provider} score=${result.score} issues=${result.issues.join(",")}`)
      }
    }

    processedSinceCheckpoint += chunk.length
    if (processedSinceCheckpoint >= BATCH_SIZE) {
      saveDrafts(state)
      processedSinceCheckpoint = 0
    }

    if (RATE_DELAY_MS > 0 && offset + CONCURRENCY < queue.length) {
      await sleep(RATE_DELAY_MS)
    }
  }

  saveDrafts(state)

  console.log("---")
  console.log(`Ready          : ${success}`)
  console.log(`Needs review   : ${needsReview}`)
  console.log(`Failed         : ${failed}`)
  console.log(`Drafts file    : ${OUTPUT_DRAFTS_FILE}`)
}

main().catch((err) => {
  console.error("Fatal:", err)
  process.exit(1)
})
