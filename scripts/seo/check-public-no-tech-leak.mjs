// scripts/seo/check-public-no-tech-leak.mjs
//
// Scans user-facing source (app/, components/, content/seo-ready/, etc.)
// for any phrase that would expose internal AI / pipeline details to end
// users. Back-end folders (scripts/seo/**, data/seo/**, dist/seo/**) are
// excluded — they are allowed to mention any of these terms.
//
// The list focuses on phrases that are unambiguously internal-tech leaks
// (e.g. "AI provider", "prompt bank", "route manifest", brand names like
// Groq/Cerebras/Gemini/Nvidia/Modal). Words like "model" or "provider" on
// their own occur naturally in real-world copy ("business model", schema.org
// `provider` JSON-LD) and are not flagged as such — they are only flagged
// when used in tech-pipeline phrasing.

import { existsSync, readdirSync, readFileSync, statSync } from "fs"
import { dirname, extname, join, relative } from "path"
import { fileURLToPath } from "url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, "../..")

const SCAN_ROOTS = [
  "app",
  "src/app",
  "pages",
  "src/pages",
  "components",
  "src/components",
  "content/seo-ready",
]

const SKIP_DIRS = new Set([
  "node_modules",
  ".git",
  ".next",
  "out",
  "dist",
  "data",
  "scripts",
])

const ALLOWED_EXT = new Set([
  ".tsx",
  ".ts",
  ".jsx",
  ".js",
  ".mjs",
  ".cjs",
  ".md",
  ".mdx",
  ".html",
])

const BANNED = [
  // Brand / provider names that should never appear on the public site.
  { label: "AI provider", regex: /\bAI provider\b/i },
  { label: "Groq", regex: /\bGroq\b/ },
  { label: "Cerebras", regex: /\bCerebras\b/ },
  { label: "Cloudflare AI", regex: /\bCloudflare AI\b/i },
  { label: "Gemini", regex: /\bGemini\b/ },
  { label: "Nvidia", regex: /\bNvidia\b/i },
  { label: "Modal", regex: /\bModal\b/ },

  // Pipeline / generation phrasing.
  { label: "prompt bank", regex: /\bprompt bank\b/i },
  { label: "random prompt", regex: /\brandom prompt\b/i },
  { label: "generated by AI", regex: /\bgenerated by AI\b/i },
  { label: "route manifest", regex: /\broute manifest\b/i },
  { label: "automation pipeline", regex: /\bautomation pipeline\b/i },
  { label: "worker pipeline", regex: /\bworker pipeline\b/i },
  { label: "internal metadata", regex: /\binternal metadata\b/i },
  { label: "SEO script", regex: /\bSEO script\b/i },
  { label: "JSONL", regex: /\bJSONL\b/ },
  { label: "cron job", regex: /\bcron job\b/i },
  { label: "cron schedule", regex: /\bcron schedule\b/i },

  // Internal hash field names — these are only ever back-end identifiers.
  { label: "bodyHash", regex: /\bbodyHash\b/ },
  { label: "promptHash", regex: /\bpromptHash\b/ },
  { label: "profileHash", regex: /\bprofileHash\b/ },

  // Bare "prompt" as a noun (case-sensitive lower-case word). Avoids
  // matching the word "prompt" as a verb in normal copy where it is
  // capitalized differently.
  { label: "prompt (bare)", regex: /(?<![A-Za-z\u4e00-\u9fff])prompt(?:s)?(?![A-Za-z])/ },

  // Chinese internal phrasing.
  { label: "提示词", regex: /提示词/ },
  { label: "路由清单", regex: /路由清单/ },
  { label: "技术实现", regex: /技术实现/ },
  { label: "脚本生成", regex: /脚本生成/ },
  { label: "自动化流水线", regex: /自动化流水线/ },
  { label: "定时任务", regex: /定时任务/ },
]

function shouldSkipDir(name) {
  if (SKIP_DIRS.has(name)) return true
  if (name.startsWith(".")) return true
  return false
}

function* walk(dirPath) {
  let entries
  try {
    entries = readdirSync(dirPath, { withFileTypes: true })
  } catch {
    return
  }
  for (const e of entries) {
    const full = join(dirPath, e.name)
    if (e.isDirectory()) {
      if (shouldSkipDir(e.name)) continue
      yield* walk(full)
    } else if (e.isFile()) {
      if (ALLOWED_EXT.has(extname(e.name))) yield full
    }
  }
}

const filesToScan = []
for (const r of SCAN_ROOTS) {
  const abs = join(ROOT, r)
  if (!existsSync(abs)) continue
  try {
    const st = statSync(abs)
    if (!st.isDirectory()) continue
  } catch {
    continue
  }
  for (const f of walk(abs)) filesToScan.push(f)
}

const leaks = []
for (const file of filesToScan) {
  let content
  try {
    content = readFileSync(file, "utf8")
  } catch {
    continue
  }
  const lines = content.split(/\r?\n/)
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    for (const rule of BANNED) {
      if (rule.regex.test(line)) {
        leaks.push({
          file: relative(ROOT, file),
          line: i + 1,
          term: rule.label,
          snippet: line.trim().slice(0, 200),
        })
      }
    }
  }
}

console.log("Public tech leak report:")
console.log(`Checked files: ${filesToScan.length}`)
console.log(`Leaks: ${leaks.length}`)

if (leaks.length) {
  console.log("Leak details (first 200):")
  for (const l of leaks.slice(0, 200)) {
    console.log(`  ${l.file}:${l.line} [${l.term}] ${l.snippet}`)
  }
  process.exit(1)
}

console.log("OK")
