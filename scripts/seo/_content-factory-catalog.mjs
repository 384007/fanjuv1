export function slugify(value) {
  return String(value)
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
}

export function buildTaxonomySeeds() {
  const out = []
  const seen = new Set()
  for (const group of GROUPS) {
    for (const [rawId, zh, en] of group.items) {
      const id = slugify(rawId)
      if (seen.has(id)) throw new Error(`Duplicate taxonomy seed id: ${id}`)
      seen.add(id)
      out.push({
        id,
        zh,
        en,
        topCategory: group.topCategory,
        subCategory: group.subCategory,
        riskLevel: group.riskLevel,
        fanjuRelevanceBase: group.fanjuRelevanceBase,
        possibleAngles: group.possibleAngles,
      })
    }
  }
  return out
}

