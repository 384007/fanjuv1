function retryPrompt(basePrompt, attempt, issues) {
  if (attempt <= 1) return basePrompt.userPrompt
  const isEn = basePrompt.locale === "en"
  return [
    basePrompt.userPrompt,
    "",
    isEn
      ? `QUALITY RETRY ${attempt}: the previous draft failed these checks: ${issues.join(", ")}. Rewrite from scratch as a complete long-form article. Do not summarize. Make it longer, more specific, and structurally complete.`
      : `质量重试 ${attempt}：上一稿未通过这些检查：${issues.join("，")}。请从头重写一篇完整长文，不要摘要，不要变短，要更具体、更本地、更完整。`,
  ].join("\n")
}

function providerOrderForPrompt(prompt) {
  const lanes = (process.env.AI_PROVIDER_LANES || process.env.AI_PROVIDER_ORDER || "groq,cerebras,openrouter,nvidia,cloudflare,gemini")
    .split(",")
    .map((x) => x.trim().toLowerCase())
    .filter(Boolean)
  if (lanes.length <= 1) return lanes.join(",")

  const n = Number.parseInt(String(prompt.promptId || "").match(/(\d+)$/)?.[1] || "1", 10)
  const start = Number.isFinite(n) ? (n - 1) % lanes.length : 0
  return [...lanes.slice(start), ...lanes.slice(0, start)].join(",")
}

async function runOneAttempt(prompt, attempt, previousIssues = []) {
  const started = Date.now()
  const providerOrder = providerOrderForPrompt(prompt)
  let generation
  try {
    generation = await generateWithRouter({
      prompt: retryPrompt(prompt, attempt, previousIssues),
      system: prompt.systemInstruction,
      maxTokens: MAX_TOKENS,
      timeoutMs: TIMEOUT_MS,
      providerOrder,
    })
  } catch (err) {
    if (!AUTO_REPAIR_ARTICLE) throw err
    console.log(`[FIX]  ${prompt.promptId} all providers failed; using structured repair article`)
    generation = { provider: "structured-repair", model: "local", content: JSON.stringify(repairedArticle(prompt)) }
  }
  const elapsed = Date.now() - started

  let parsed = extractJsonObject(generation.content)
  let { score, issues } = scoreArticle(prompt, parsed)
  if (AUTO_REPAIR_ARTICLE && (score < MIN_SCORE || issues.length > 0)) {
    const repaired = repairedArticle(prompt)
    const repairedScore = scoreArticle(prompt, repaired)
    if (repairedScore.score >= MIN_SCORE && repairedScore.issues.length === 0) {
      console.log(`[FIX]  ${prompt.promptId} repaired ${issues.join(",") || "unknown"} -> score ${repairedScore.score}`)
      parsed = repaired
      score = repairedScore.score
      issues = repairedScore.issues
      generation = { ...generation, provider: `${generation.provider}+repair` }
    }
  }

  const body = String(parsed?.body || "").trim()
  const title = String(parsed?.title || "").trim()
  const description = String(parsed?.description || "").trim()
  const r2SlugBase = modelSlugForR2(prompt, parsed?.slug)
  const r2Slug = `${r2SlugBase}-${shortHash(`${prompt.promptId}:${body}`)}`
  const slug = routeSlug(prompt.route)
  const canonicalPath = prompt.route
  const alternatePath = alternatePathFor(prompt.route)
  const r2Key = r2KeyFor(prompt, r2Slug)
  const status = score >= MIN_SCORE && issues.length === 0 ? "ready" : "needs-review"

  return {
    prompt,
    generation,
    parsed,
    score,
    issues,
    title,
    description,
    body,
    bodyHtml: status === "ready" ? bodyToArticleHtml(prompt, { title, description, body }) : "",
    slug,
    canonicalPath,
    alternatePath,
    r2Key,
    status,
    elapsedMs: elapsed,
    attempt,
  }
}

async function runOne(prompt) {
  let lastResult = null
  let previousIssues = []
  for (let attempt = 1; attempt <= QUALITY_ATTEMPTS; attempt++) {
    const result = await runOneAttempt(prompt, attempt, previousIssues)
    if (result.status === "ready") return result
    lastResult = result
    previousIssues = result.issues
    console.log(`[RETRY] ${prompt.promptId} attempt=${attempt}/${QUALITY_ATTEMPTS} issues=${result.issues.join(",")}`)
    if (attempt < QUALITY_ATTEMPTS && QUALITY_RETRY_DELAY_MS > 0) {
      await sleep(QUALITY_RETRY_DELAY_MS)
    }
  }
  return lastResult
}

function sqlString(value) {
  if (value === null || value === undefined) return "NULL"
  return `'${String(value).replaceAll("'", "''")}'`
}

function sqlNumber(value) {
  const n = Number(value)
  return Number.isFinite(n) ? String(Math.trunc(n)) : "NULL"
}

function articleUpsertSql(entry) {
  const columns = [
    "slug",
    "lang",
    "city_slug",
    "topic_slug",
    "title",
    "description",
    "canonical_path",
    "alternate_path",
    "r2_key",
    "body_html",
    "status",
    "quality_score",
    "prompt_id",
    "prompt_hash",
    "profile_hash",
    "body_hash",
    "provider",
    "model",
    "published_at",
    "updated_at",
  ]
  const values = [
    sqlString(entry.slug),
    sqlString(entry.locale),
    sqlString(entry.citySlug),
    sqlString(entry.topicSlug),
    sqlString(entry.title),
    sqlString(entry.description),
    sqlString(entry.canonicalPath),
    sqlString(entry.alternatePath),
    sqlString(entry.r2Key),
    sqlString(entry.bodyHtml),
    sqlString("ready"),
    sqlNumber(entry.score),
    sqlString(entry.promptId),
    sqlString(entry.promptHash),
    sqlString(entry.profileHash),
    sqlString(entry.bodyHash),
    sqlString(entry.provider),
    sqlString(entry.model),
    sqlString(entry.publishedAt),
    sqlString(entry.publishedAt),
  ]

  const updates = columns
    .filter((column) => column !== "slug")
    .map((column) => `${column}=excluded.${column}`)
    .join(", ")

  return `INSERT INTO articles (${columns.join(", ")}) VALUES (${values.join(", ")}) ON CONFLICT(slug) DO UPDATE SET ${updates};`
}

async function ensureCloudflareColumns() {
  if (DRY_RUN) return
  const sql = [
    "ALTER TABLE articles ADD COLUMN prompt_id TEXT;",
    "ALTER TABLE articles ADD COLUMN prompt_hash TEXT;",
    "ALTER TABLE articles ADD COLUMN profile_hash TEXT;",
    "ALTER TABLE articles ADD COLUMN body_hash TEXT;",
    "ALTER TABLE articles ADD COLUMN provider TEXT;",
    "ALTER TABLE articles ADD COLUMN model TEXT;",
    "ALTER TABLE articles ADD COLUMN published_at TEXT;",
    "ALTER TABLE articles ADD COLUMN body_html TEXT;",
  ]

  for (const command of sql) {
    try {
      await d1Query(command)
    } catch (err) {
      const text = err.message || ""
      if (!/duplicate column name|already exists/i.test(text)) throw err
    }
  }
}

async function cloudflareFetch(path, init = {}) {
  const controller = new AbortController()
  const timeout = setTimeout(() => controller.abort(), CF_TIMEOUT_MS)
  let res
  try {
    res = await fetch(`https://api.cloudflare.com/client/v4${path}`, {
      ...init,
      signal: controller.signal,
      headers: {
        Authorization: `Bearer ${CLOUDFLARE_API_TOKEN}`,
        ...(init.headers || {}),
      },
    })
  } catch (err) {
    if (err?.name === "AbortError") {
      throw new Error(`Cloudflare API timeout after ${CF_TIMEOUT_MS}ms: ${path}`)
    }
    throw err
  } finally {
    clearTimeout(timeout)
  }
  const text = await res.text()
  let json = null
  try {
    json = text ? JSON.parse(text) : null
  } catch {
    // R2 object uploads can return an empty or non-JSON body.
  }

  if (!res.ok || json?.success === false) {
    const message = json?.errors?.map((e) => `${e.code || "error"}: ${e.message}`).join("; ") || text || res.statusText
    throw new Error(`Cloudflare API ${res.status} ${path}: ${message}`)
  }

  return json
}

async function d1Query(sql, params = []) {
  return cloudflareFetch(`/accounts/${CLOUDFLARE_ACCOUNT_ID}/d1/database/${CLOUDFLARE_D1_DATABASE_ID}/query`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ sql, params }),
  })
}

async function uploadR2(entry) {
  const file = join(TMP_DIR, `${entry.promptId}.html`)
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, entry.bodyHtml, "utf8")
  await cloudflareFetch(`/accounts/${CLOUDFLARE_ACCOUNT_ID}/r2/buckets/${CLOUDFLARE_R2_BUCKET}/objects/${encodeR2Key(entry.r2Key)}`, {
    method: "PUT",
    headers: { "Content-Type": "text/html; charset=utf-8" },
    body: readFileSync(file),
  })
}

async function upsertD1(entries) {
  if (!entries.length) return
  const file = join(TMP_DIR, `d1-upsert-${Date.now()}.sql`)
  mkdirSync(dirname(file), { recursive: true })
  const sql = entries.map(articleUpsertSql).join("\n")
  writeFileSync(file, sql + "\n", "utf8")
  for (const entry of entries) {
    await d1Query(articleUpsertSql(entry))
  }
}

function encodeR2Key(key) {
  return String(key).split("/").map(encodeURIComponent).join("/")
}

