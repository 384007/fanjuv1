function extractJsonObject(text) {
  if (!text) return null
  const trimmed = text.trim()
  const fenced = trimmed
    .replace(/^```(?:json)?\s*/i, "")
    .replace(/\s*```$/i, "")
    .trim()

  const candidates = [trimmed, fenced]
  for (const c of candidates) {
    try {
      const parsed = JSON.parse(c)
      if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) return parsed
    } catch {
      // continue
    }
  }

  for (const candidate of candidates) {
    let depth = 0
    let start = -1
    let bestStart = -1
    let bestEnd = -1
    let inStr = false
    let escape = false
    for (let i = 0; i < candidate.length; i++) {
      const ch = candidate[i]
      if (escape) {
        escape = false
        continue
      }
      if (ch === "\\") {
        escape = true
        continue
      }
      if (ch === '"') {
        inStr = !inStr
        continue
      }
      if (inStr) continue
      if (ch === "{") {
        if (depth === 0) start = i
        depth++
      } else if (ch === "}") {
        depth--
        if (depth === 0 && start !== -1) {
          bestStart = start
          bestEnd = i + 1
        }
      }
    }
    if (bestStart !== -1 && bestEnd !== -1) {
      try {
        return JSON.parse(candidate.slice(bestStart, bestEnd))
      } catch {
        // fall through
      }
    }
  }
  return null
}

function isMostlyChinese(s) {
  const total = s.length
  if (total === 0) return false
  const chinese = (s.match(/[\u4e00-\u9fff]/g) || []).length
  return chinese / total > 0.3
}

function isMostlyEnglish(s) {
  const total = s.length
  if (total === 0) return false
  const ascii = (s.match(/[A-Za-z]/g) || []).length
  return ascii / total > 0.4
}

function countMarkdownHeadings(body, level = 2) {
  const marker = "#".repeat(level)
  return (String(body).match(new RegExp(`^${marker}\\s+`, "gm")) || []).length
}

function countParagraphs(body) {
  return String(body)
    .split(/\n{2,}/)
    .map((part) => part.trim())
    .filter((part) => part && !part.startsWith("#") && !/^[-*]\s+/m.test(part))
    .length
}

function includesCity(prompt, text) {
  const city = String(prompt.cityNameLocalized || "").trim()
  if (!city) return true
  if (prompt.locale === "en") return text.toLowerCase().includes(city.toLowerCase())
  return text.includes(city)
}

function scoreArticle(prompt, parsed) {
  const issues = []
  if (!parsed) return { score: 0, issues: ["json-parse-failed"] }
  if (!parsed.title) issues.push("missing-title")
  if (!parsed.body) issues.push("missing-body")
  if (!parsed.description) issues.push("missing-description")
  if (parsed.locale && parsed.locale !== prompt.locale) issues.push("locale-mismatch")

  const body = String(parsed.body || "")
  const title = String(parsed.title || "")
  const description = String(parsed.description || "")
  const haystack = `${title}\n${description}\n${body}`

  const leakHits = detectLeaks(haystack)
  if (leakHits.length) issues.push(`tech-leak:${leakHits.length}`)

  if (prompt.locale === "zh" && !isMostlyChinese(body)) issues.push("body-not-chinese")
  if (prompt.locale === "en" && !isMostlyEnglish(body)) issues.push("body-not-english")

  const minLen = prompt.locale === "en" ? 3200 : 2200
  if (body.length < minLen) issues.push(`body-too-short:${body.length}`)
  if (body.length > (prompt.locale === "en" ? 9000 : 5200)) issues.push(`body-too-long:${body.length}`)
  if (prompt.locale === "en" && !/Fanju app/i.test(`${title}\n${description}\n${body.slice(0, 600)}`)) {
    issues.push("missing-primary-keyword:fanju-app")
  }
  if (prompt.locale === "zh" && !`${title}\n${description}\n${body.slice(0, 600)}`.includes("饭局app")) {
    issues.push("missing-primary-keyword:饭局app")
  }
  if (!includesCity(prompt, `${title}\n${description}\n${body.slice(0, 1200)}`)) issues.push("missing-city-context")
  if (countMarkdownHeadings(body, 2) < 5) issues.push(`too-few-h2:${countMarkdownHeadings(body, 2)}`)
  if (countMarkdownHeadings(body, 3) < 1) issues.push(`too-few-h3:${countMarkdownHeadings(body, 3)}`)
  if (countParagraphs(body) < 8) issues.push(`too-few-paragraphs:${countParagraphs(body)}`)

  if (issues.length === 0) return { score: 100, issues }
  if (issues.some((s) => s.startsWith("tech-leak") || s.startsWith("missing-primary-keyword") || s === "missing-city-context" || s.startsWith("too-few") || s === "locale-mismatch" || s === "body-not-chinese" || s === "body-not-english" || s === "json-parse-failed")) {
    return { score: 0, issues }
  }

  let score = 100
  if (issues.find((x) => x.startsWith("body-too-short"))) score -= 12
  if (issues.includes("missing-description")) score -= 8
  if (issues.includes("missing-title")) score -= 30
  return { score: Math.max(score, 0), issues }
}

function escapeHtml(input = "") {
  return String(input)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;")
}

function inlineMarkdown(text = "") {
  return escapeHtml(text)
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
    .replace(/\*([^*]+)\*/g, "<em>$1</em>")
}

function bodyToArticleHtml(prompt, result) {
  const lines = String(result.body || "").replace(/\r\n/g, "\n").split("\n")
  const html = []
  let paragraph = []
  let list = []

  const flushParagraph = () => {
    if (!paragraph.length) return
    html.push(`<p>${inlineMarkdown(paragraph.join(" ").trim())}</p>`)
    paragraph = []
  }

  const flushList = () => {
    if (!list.length) return
    html.push(`<ul>${list.map((item) => `<li>${inlineMarkdown(item)}</li>`).join("")}</ul>`)
    list = []
  }

  for (const rawLine of lines) {
    const line = rawLine.trim()
    if (!line) {
      flushParagraph()
      flushList()
      continue
    }

    const heading = line.match(/^(#{2,4})\s+(.+)$/)
    if (heading) {
      flushParagraph()
      flushList()
      const level = heading[1].length
      html.push(`<h${level}>${inlineMarkdown(heading[2].trim())}</h${level}>`)
      continue
    }

    const bullet = line.match(/^[-*]\s+(.+)$/)
    if (bullet) {
      flushParagraph()
      list.push(bullet[1].trim())
      continue
    }

    flushList()
    paragraph.push(line)
  }

  flushParagraph()
  flushList()

  return [
    `<article>`,
    `<h1>${escapeHtml(result.title)}</h1>`,
    `<p class="dek">${escapeHtml(result.description)}</p>`,
    ...html,
    `</article>`,
  ].join("\n")
}

