function modelSlugForR2(prompt, parsedSlug = "") {
  const cleaned = String(parsedSlug || "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .replace(/-{2,}/g, "-")
  if (cleaned && /^[a-z0-9][a-z0-9-]{2,80}$/.test(cleaned)) return cleaned
  const short = (prompt.profileHash || "").slice(0, 8) || "x"
  return `${prompt.locale}-${prompt.citySlug}-${prompt.topicSlug}-${short}`.toLowerCase()
}

