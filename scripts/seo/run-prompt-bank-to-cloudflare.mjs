function zhHeadingLatinNoise(body = "") {
  const headings = [...String(body || "").matchAll(/^#{1,3}\s+(.+)$/gm)]
    .map((m) => m[1].trim())
    .filter(Boolean)
  const words = new Set()
  for (const heading of headings) {
    for (const word of latinNoiseInZhHeading(heading)) words.add(word)
  }
  return [...words]
}

