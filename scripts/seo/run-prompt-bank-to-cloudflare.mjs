function loadPromptBank() {
  if (!existsSync(PROMPT_BANK_FILE)) {
    console.error(`Missing prompt bank file: ${PROMPT_BANK_FILE}`)
    console.error("Run: pnpm seo:prompt-bank")
    process.exit(1)
  }

  const raw = readFileSync(PROMPT_BANK_FILE, "utf8")
  const out = []
  let lineNo = 0
  for (const line of raw.split(/\r?\n/)) {
    lineNo++
    const trimmed = line.trim()
    if (!trimmed) continue
    try {
      out.push(JSON.parse(trimmed))
    } catch (err) {
      console.error(`Failed to parse prompt bank line ${lineNo}: ${err.message}`)
      process.exit(1)
    }
  }

  if (out.length === 0) {
    console.error("Prompt bank is empty.")
    console.error("Run: pnpm seo:prompt-bank")
    process.exit(1)
  }
  return out
}

function loadJsonState(file, fallback) {
  if (!existsSync(file)) return fallback
  try {
    const parsed = JSON.parse(readFileSync(file, "utf8"))
    return parsed && typeof parsed === "object" ? parsed : fallback
  } catch {
    console.warn(`Existing JSON state unreadable: ${file}; starting fresh.`)
    return fallback
  }
}

function parseFrontmatter(raw) {
  const match = String(raw || "").match(/^---\r?\n([\s\S]*?)\r?\n---/)
  if (!match) return {}
  const meta = {}
  for (const line of match[1].split("\n")) {
    const m = line.match(/^(\w+):\s*(.*)\s*$/)
    if (!m) continue
    let value = m[2].trim()
    const quote = value[0]
    if ((quote === "\"" || quote === "'") && value.endsWith(quote)) {
      value = value.slice(1, -1)
      value = quote === "\""
        ? value.replace(/\\"/g, "\"")
        : value.replace(/\\'/g, "'")
      value = value.replace(/\\\\/g, "\\")
    }
    meta[m[1]] = value.trim()
  }
  return meta
}

function normalizeCanonicalPath(p) {
  if (!p) return ""
  let path = String(p).trim()
  if (/^https?:\/\//i.test(path)) {
    try {
      path = new URL(path).pathname
    } catch {
      return ""
    }
  }
  path = path.startsWith("/") ? path : `/${path}`
  return path.endsWith("/") && path.length > 1 ? path.slice(0, -1) : path
}

