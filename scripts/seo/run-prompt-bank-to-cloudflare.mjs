function escapeHtml(input = "") {
  return String(input)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;")
}

function inlineMarkdown(text = "") {
  return escapeHtml(stripPublicLinks(text))
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
    .replace(/\*([^*]+)\*/g, "<em>$1</em>")
}

function bodyToArticleHtml(prompt, result) {
  const lines = String(result.body || "").replace(/\r\n/g, "\n").split("\n")
  const html = []
  let paragraph = []
  let list = []
  let listType = ""

  const flushParagraph = () => {
    if (!paragraph.length) return
    html.push(`<p>${inlineMarkdown(paragraph.join(" ").trim())}</p>`)
    paragraph = []
  }

  const flushList = () => {
    if (!list.length) return
    const tag = listType === "ol" ? "ol" : "ul"
    html.push(`<${tag}>${list.map((item) => `<li>${inlineMarkdown(item)}</li>`).join("")}</${tag}>`)
    list = []
    listType = ""
  }

  for (const rawLine of lines) {
    const line = rawLine.trim()
    if (!line) {
      flushParagraph()
      flushList()
      continue
    }

    const heading = line.match(/^(#{2,4})\s+(.+)$/)
    if (heading) {
      flushParagraph()
      flushList()
      const level = heading[1].length
      html.push(`<h${level}>${inlineMarkdown(heading[2].trim())}</h${level}>`)
      continue
    }

    const bullet = line.match(/^[-*]\s+(.+)$/)
    if (bullet) {
      flushParagraph()
      if (listType && listType !== "ul") flushList()
      listType = "ul"
      list.push(bullet[1].trim())
      continue
    }

    const ordered = line.match(/^\d+\.\s+(.+)$/)
    if (ordered) {
      flushParagraph()
      if (listType && listType !== "ol") flushList()
      listType = "ol"
      list.push(ordered[1].trim())
      continue
    }

    flushList()
    paragraph.push(line)
  }

  flushParagraph()
  flushList()

  return [
    `<article>`,
    ...html,
    `</article>`,
  ].join("\n")
}

