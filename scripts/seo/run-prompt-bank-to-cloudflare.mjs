function loadPromptBank() {
  if (!existsSync(PROMPT_BANK_FILE)) {
    console.error(`Missing prompt bank file: ${PROMPT_BANK_FILE}`)
    console.error("Run: pnpm seo:prompt-bank")
    process.exit(1)
  }

  const raw = readFileSync(PROMPT_BANK_FILE, "utf8")
  const out = []
  let lineNo = 0
  for (const line of raw.split(/\r?\n/)) {
    lineNo++
    const trimmed = line.trim()
    if (!trimmed) continue
    try {
      out.push(JSON.parse(trimmed))
    } catch (err) {
      console.error(`Failed to parse prompt bank line ${lineNo}: ${err.message}`)
      process.exit(1)
    }
  }

  if (out.length === 0) {
    console.error("Prompt bank is empty.")
    console.error("Run: pnpm seo:prompt-bank")
    process.exit(1)
  }
  return out
}

function loadJsonState(file, fallback) {
  if (!existsSync(file)) return fallback
  try {
    const parsed = JSON.parse(readFileSync(file, "utf8"))
    return parsed && typeof parsed === "object" ? parsed : fallback
  } catch {
    console.warn(`Existing JSON state unreadable: ${file}; starting fresh.`)
    return fallback
  }
}

function saveJsonState(file, state) {
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, JSON.stringify(state, null, 2) + "\n", "utf8")
}

