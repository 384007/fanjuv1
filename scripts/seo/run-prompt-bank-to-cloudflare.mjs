function stripMarkdownFence(text) {
  return String(text || "")
    .trim()
    .replace(/^```(?:markdown|md|json)?\s*/i, "")
    .replace(/\s*```$/i, "")
    .trim()
}

function normalizeMarkdownHeadingSpacing(text = "") {
  return String(text || "")
    .replace(/\r\n/g, "\n")
    .split("\n")
    .map((line) => {
      const heading = line.match(/^(#{1,10})(?!#)(\S.*)$/)
      if (!heading) return line
      return `${heading[1]} ${heading[2].trim()}`
    })
    .join("\n")
    .trim()
}

function expectedPromptHeadings(prompt, marker = "##") {
  const headingPattern = new RegExp(`^${marker.replaceAll("#", "\\#")}\\s+(.+)$`, "gm")
  return new Set(
    [...String(prompt?.userPrompt || "").matchAll(headingPattern)]
      .map((m) => m[1].trim())
      .filter(Boolean)
  )
}

function cleanMetaDescriptionText(value = "") {
  return String(value || "")
    .replace(/^#{1,10}\s+.+$/gm, " ")
    .replace(/^[-*]\s+/gm, " ")
    .replace(/\s+/g, " ")
    .trim()
}

function trimMetaDescription(value = "", locale = "zh") {
  const max = locale === "en" ? 220 : 120
  const cleaned = cleanMetaDescriptionText(value)
  if (cleaned.length <= max) return cleaned
  const cut = cleaned.slice(0, max)
  return locale === "en"
    ? cut.replace(/\s+\S*$/, "").trim() || cut.trim()
    : cut.trim()
}

function metaDescriptionForArticle(prompt, body = "", firstParagraph = "") {
  const paragraphs = publicParagraphs(body)
    .map(cleanMetaDescriptionText)
    .filter(Boolean)
  const introSig = openingFingerprint(prompt, firstParagraph)
  const candidates = paragraphs
    .slice(1)
    .filter((paragraph) => {
      const sig = openingFingerprint(prompt, paragraph)
      return sig && sig !== introSig
    })
  let description = candidates.find((paragraph) => includesCity(prompt, paragraph)) || candidates[0] || firstParagraph
  if (!includesCity(prompt, description)) {
    const city = String(prompt.cityNameLocalized || prompt.cityNameZh || prompt.cityNameEn || prompt.citySlug || "").trim()
    if (city) description = prompt.locale === "en" ? `${city}: ${description}` : `${city}：${description}`
  }
  return trimMetaDescription(description, prompt.locale)
}

function extractMarkdownArticle(prompt, text) {
  const cleaned = repairHeadings(prompt, normalizeMarkdownHeadingSpacing(stripMarkdownFence(text)))
  if (!cleaned || looksLikeJsonWrapper(cleaned)) return null
  if (!/^#\s+.+$/m.test(cleaned)) return null
  if (countMarkdownHeadings(cleaned, 2) < 6) return null

  const h1 = cleaned.match(/^#\s+(.+)$/m)
  const firstParagraph = cleaned
    .split(/\n{2,}/)
    .map((part) => part.trim())
    .find((part) => part && !part.startsWith("#") && !/^[-*]\s+/m.test(part))
  if (!h1?.[1] || !firstParagraph) return null

  return {
    title: h1[1].trim(),
    description: metaDescriptionForArticle(prompt, cleaned, firstParagraph),
    body: cleaned,
    slug: modelSlugForR2(prompt),
    locale: prompt.locale,
  }
}

function parseModelArticle(prompt, content) {
  return extractMarkdownArticle(prompt, content)
}

function looksLikeJsonWrapper(text = "") {
  const s = String(text || "").trim()
  if (!s) return false
  if (/^\{[\s\S]*"title"\s*:/i.test(s)) return true
  if (/^\{[\s\S]*"body"\s*:/i.test(s)) return true
  if (/"(?:title|description|body|locale|slug)"\s*:/i.test(s.slice(0, 900))) return true
  return false
}

function isMostlyChinese(s) {
  const total = s.length
  if (total === 0) return false
  const chinese = (s.match(/[\u4e00-\u9fff]/g) || []).length
  return chinese / total > 0.3
}

function isMostlyEnglish(s) {
  const total = s.length
  if (total === 0) return false
  const ascii = (s.match(/[A-Za-z]/g) || []).length
  return ascii / total > 0.4
}

function countMarkdownHeadings(body, level = 2) {
  const marker = "#".repeat(level)
  return (String(body).match(new RegExp(`^${marker}\\s+`, "gm")) || []).length
}

function countParagraphs(body) {
  return publicParagraphs(body)
    .length
}

function paragraphBlocks(body = "") {
  return String(body || "")
    .replace(/^#{1,10}\s+.+$/gm, "\n")
    .split(/\n{2,}/)
    .map((part) => part.trim())
    .filter((part) => part && !part.startsWith("#") && !/^[-*]\s+/m.test(part))
}

function duplicateMarkdownHeadings(body, level = 2) {
  const marker = "#".repeat(level)
  const headings = [...String(body).matchAll(new RegExp(`^${marker}\\s+(.+)$`, "gm"))]
    .map((m) => m[1].trim().toLowerCase())
    .filter(Boolean)
  return headings.length - new Set(headings).size
}

function duplicateMarkdownHeadingDetails(body = "") {
  const seen = new Map()
  const duplicates = []
  for (const heading of markdownHeadings(body)) {
    const normalized = normalizeForTemplateCheck(heading.text)
    if (!normalized) continue
    const label = `H${heading.level}:${heading.text}`
    if (seen.has(normalized)) {
      duplicates.push({ normalized, first: seen.get(normalized), duplicate: label })
    } else {
      seen.set(normalized, label)
    }
  }
  return duplicates
}

function duplicateMarkdownHeadingTexts(body = "") {
  return duplicateMarkdownHeadingDetails(body).length
}

function duplicateParagraphs(body) {
  const paragraphs = paragraphBlocks(body)
    .map((part) => part
      .replace(/^#+\s*/, "")
      .replace(/\s+/g, "")
      .replace(/[，。,.!?！？、；;：:"'“”‘’()（）[\]【】]/g, "")
      .toLowerCase())
    .filter((part) => part.length >= 80)
  return paragraphs.length - new Set(paragraphs).size
}

function publicParagraphs(body = "") {
  return paragraphBlocks(body)
    .filter((part) => !/^\d+\.\s+/m.test(part))
}

function markdownH1(body = "") {
  return String(body || "").match(/^#\s+(.+)$/m)?.[1]?.trim() || ""
}

function markdownHeadings(body = "") {
  return [...String(body || "").matchAll(/^(#{1,10})\s+(.+)$/gm)]
    .map((m) => ({ level: m[1].length, text: m[2].trim() }))
    .filter((item) => item.text)
}

function normalizeForTemplateCheck(value = "") {
  return String(value || "")
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\u4e00-\u9fff]+/gu, " ")
    .replace(/\s+/g, " ")
    .trim()
}

function compactCjk(value = "") {
  return String(value || "")
    .replace(/\s+/g, "")
    .replace(/[，。,.!?！？、；;：:"'“”‘’()（）[\]【】|｜-]/g, "")
    .toLowerCase()
}

function stripRouteVariables(prompt, value = "") {
  const replacements = [
    prompt.cityNameLocalized,
    prompt.cityNameZh,
    prompt.cityNameEn,
    prompt.citySlug,
    String(prompt.citySlug || "").replace(/-/g, " "),
    prompt.topicNameLocalized,
    prompt.topicSlug,
    String(prompt.topicSlug || "").replace(/-/g, " "),
  ].filter(Boolean)

  let out = String(value || "")
  for (const item of replacements) {
    out = out.replace(new RegExp(escapeRegExp(item), "gi"), " ")
  }
  return out
    .replace(/Fanju\s*app/gi, " ")
    .replace(/Fanju\s*\/\s*饭局/gi, " ")
    .replace(/饭局\s*app/gi, " ")
    .replace(/饭局/g, " ")
}

function textFingerprint(prompt, value = "", min = 60, max = 180) {
  const cleaned = stripRouteVariables(prompt, value)
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\u4e00-\u9fff]+/gu, "")
    .trim()
  if (cleaned.length < min) return ""
  return cleaned.slice(0, max)
}

function openingFingerprint(prompt, value = "") {
  const normalized = String(value || "")
    .toLowerCase()
    .replace(/[，。,.!?！？、；;：:"'“”‘’()（）[\]【】]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
  if (!normalized) return ""
  if (prompt.locale === "en") return normalized.split(/\s+/).slice(0, 10).join(" ")
  return normalized.replace(/\s+/g, "").slice(0, 28)
}

function repeatedOpeningIssues(prompt, body = "") {
  const seen = new Map()
  const issues = []
  for (const paragraph of publicParagraphs(body)) {
    const sig = openingFingerprint(prompt, paragraph)
    if (!sig || sig.length < (prompt.locale === "en" ? 24 : 12)) continue
    seen.set(sig, (seen.get(sig) || 0) + 1)
  }
  for (const [sig, count] of seen.entries()) {
    if (count > 1) issues.push(`repeated-paragraph-opening:${sig.slice(0, 60)}`)
  }
  return issues.slice(0, 4)
}

function nearDuplicateParagraphIssues(prompt, body = "") {
  const paragraphs = publicParagraphs(body)
  const seen = new Map()
  const issues = []
  for (let i = 0; i < paragraphs.length; i++) {
    const sig = textFingerprint(prompt, paragraphs[i], prompt.locale === "en" ? 140 : 80, prompt.locale === "en" ? 260 : 180)
    if (!sig) continue
    if (seen.has(sig)) issues.push(`near-duplicate-paragraph:${seen.get(sig) + 1}->${i + 1}`)
    else seen.set(sig, i)
  }

  const introSig = textFingerprint(prompt, paragraphs[0] || "", prompt.locale === "en" ? 120 : 70, prompt.locale === "en" ? 240 : 160)
  if (introSig) {
    for (let i = 1; i < paragraphs.length; i++) {
      const sig = textFingerprint(prompt, paragraphs[i], prompt.locale === "en" ? 120 : 70, prompt.locale === "en" ? 240 : 160)
      if (sig && sig === introSig) issues.push(`intro-repeated-in-body:${i + 1}`)
    }
  }

  return issues.slice(0, 4)
}

function escapeRegExp(value = "") {
  return String(value).replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
}

