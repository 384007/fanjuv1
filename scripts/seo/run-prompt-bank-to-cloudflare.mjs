function stripMarkdownFence(text) {
  return String(text || "")
    .trim()
    .replace(/^```(?:markdown|md|json)?\s*/i, "")
    .replace(/\s*```$/i, "")
    .trim()
}

function normalizeMarkdownHeadingSpacing(text = "") {
  return String(text || "")
    .replace(/\r\n/g, "\n")
    .split("\n")
    .map((line) => {
      const heading = line.match(/^(#{1,10})(?!#)(\S.*)$/)
      if (!heading) return line
      return `${heading[1]} ${heading[2].trim()}`
    })
    .join("\n")
    .trim()
}

