function extractJsonObject(text) {
  if (!text) return null
  const trimmed = text.trim()
  const fenced = trimmed
    .replace(/^```(?:json)?\s*/i, "")
    .replace(/\s*```$/i, "")
    .trim()

  const candidates = [trimmed, fenced]
  for (const c of candidates) {
    try {
      const parsed = JSON.parse(c)
      if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) return parsed
    } catch {
      // continue
    }
  }

  for (const candidate of candidates) {
    let depth = 0
    let start = -1
    let bestStart = -1
    let bestEnd = -1
    let inStr = false
    let escape = false
    for (let i = 0; i < candidate.length; i++) {
      const ch = candidate[i]
      if (escape) {
        escape = false
        continue
      }
      if (ch === "\\") {
        escape = true
        continue
      }
      if (ch === '"') {
        inStr = !inStr
        continue
      }
      if (inStr) continue
      if (ch === "{") {
        if (depth === 0) start = i
        depth++
      } else if (ch === "}") {
        depth--
        if (depth === 0 && start !== -1) {
          bestStart = start
          bestEnd = i + 1
        }
      }
    }
    if (bestStart !== -1 && bestEnd !== -1) {
      try {
        return JSON.parse(candidate.slice(bestStart, bestEnd))
      } catch {
        // fall through
      }
    }
  }
  return null
}

function unescapeLooseJsonString(value = "") {
  return String(value)
    .replace(/\\n/g, "\n")
    .replace(/\\r/g, "")
    .replace(/\\t/g, "\t")
    .replace(/\\"/g, '"')
    .replace(/\\\\/g, "\\")
    .trim()
}

function extractLooseJsonArticle(prompt, text) {
  const cleaned = stripMarkdownFence(text)
  if (!/"title"\s*:/i.test(cleaned) || !/"body"\s*:/i.test(cleaned)) return null

  const title = cleaned.match(/"title"\s*:\s*"([\s\S]*?)"\s*,\s*"description"\s*:/i)?.[1]
  const description = cleaned.match(/"description"\s*:\s*"([\s\S]*?)"\s*,\s*"body"\s*:/i)?.[1]
  let body = cleaned.match(/"body"\s*:\s*"([\s\S]*?)"\s*,\s*"slug"\s*:/i)?.[1]
    || cleaned.match(/"body"\s*:\s*"([\s\S]*?)"\s*,\s*"locale"\s*:/i)?.[1]
    || cleaned.match(/"body"\s*:\s*"([\s\S]*?)"\s*}\s*$/i)?.[1]
  if (!body) {
    const bodyStart = cleaned.match(/"body"\s*:\s*"/i)
    if (bodyStart?.index !== undefined) {
      const start = bodyStart.index + bodyStart[0].length
      const tail = cleaned.slice(start)
      const meta = tail.match(/"\s*,\s*"(?:slug|locale|route)"\s*:/i)
      const end = meta?.index ?? tail.lastIndexOf('"')
      body = end > 0 ? tail.slice(0, end) : tail
    }
  }

  if (!title || !description || !body) return null
  return {
    title: unescapeLooseJsonString(title),
    description: unescapeLooseJsonString(description),
    body: unescapeLooseJsonString(body),
    slug: modelSlugForR2(prompt),
    locale: prompt.locale,
  }
}

function stripMarkdownFence(text) {
  return String(text || "")
    .trim()
    .replace(/^```(?:markdown|md|json)?\s*/i, "")
    .replace(/\s*```$/i, "")
    .trim()
}

function extractMarkdownArticle(prompt, text) {
  const cleaned = stripMarkdownFence(text)
  if (!cleaned || looksLikeJsonWrapper(cleaned)) return null
  if (!/^#\s+.+$/m.test(cleaned)) return null
  if (countMarkdownHeadings(cleaned, 2) < 5) return null

  const h1 = cleaned.match(/^#\s+(.+)$/m)
  const firstParagraph = cleaned
    .split(/\n{2,}/)
    .map((part) => part.trim())
    .find((part) => part && !part.startsWith("#") && !/^[-*]\s+/m.test(part))
  if (!h1?.[1] || !firstParagraph) return null

  return {
    title: h1[1].trim(),
    description: firstParagraph.replace(/\s+/g, " ").slice(0, prompt.locale === "en" ? 220 : 120),
    body: cleaned,
    slug: modelSlugForR2(prompt),
    locale: prompt.locale,
  }
}

function parseModelArticle(prompt, content) {
  return extractJsonObject(content) || extractLooseJsonArticle(prompt, content) || extractMarkdownArticle(prompt, content)
}

function looksLikeJsonWrapper(text = "") {
  const s = String(text || "").trim()
  if (!s) return false
  if (/^\{[\s\S]*"title"\s*:/i.test(s)) return true
  if (/^\{[\s\S]*"body"\s*:/i.test(s)) return true
  if (/"(?:title|description|body|locale|slug)"\s*:/i.test(s.slice(0, 900))) return true
  return false
}

function isMostlyChinese(s) {
  const total = s.length
  if (total === 0) return false
  const chinese = (s.match(/[\u4e00-\u9fff]/g) || []).length
  return chinese / total > 0.3
}

function isMostlyEnglish(s) {
  const total = s.length
  if (total === 0) return false
  const ascii = (s.match(/[A-Za-z]/g) || []).length
  return ascii / total > 0.4
}

function countMarkdownHeadings(body, level = 2) {
  const marker = "#".repeat(level)
  return (String(body).match(new RegExp(`^${marker}\\s+`, "gm")) || []).length
}

function countParagraphs(body) {
  return String(body)
    .split(/\n{2,}/)
    .map((part) => part.trim())
    .filter((part) => part && !part.startsWith("#") && !/^[-*]\s+/m.test(part))
    .length
}

function duplicateMarkdownHeadings(body, level = 2) {
  const marker = "#".repeat(level)
  const headings = [...String(body).matchAll(new RegExp(`^${marker}\\s+(.+)$`, "gm"))]
    .map((m) => m[1].trim().toLowerCase())
    .filter(Boolean)
  return headings.length - new Set(headings).size
}

function duplicateParagraphs(body) {
  const paragraphs = String(body)
    .split(/\n{2,}/)
    .map((part) => part
      .replace(/^#+\s*/, "")
      .replace(/\s+/g, "")
      .replace(/[，。,.!?！？、；;：:"'“”‘’()（）[\]【】]/g, "")
      .toLowerCase())
    .filter((part) => part.length >= 80)
  return paragraphs.length - new Set(paragraphs).size
}

function repeatedPhraseHits(body) {
  const text = String(body || "")
  const phrases = [
    /can meet anyone's needs/gi,
    /can satisfy anyone's needs/gi,
    /can meet different needs/gi,
    /可以满足任何人的需求/g,
    /可以找到适合自己的/g,
    /并与新朋友相遇/g,
    /非常多样化/g,
  ]
  return phrases.reduce((sum, pattern) => {
    const hits = text.match(pattern)
    return sum + (hits && hits.length > 2 ? hits.length - 2 : 0)
  }, 0)
}

