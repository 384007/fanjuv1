function sourcePathForEntry(entry) {
  return entry.sourcePath || `content/seo-ready/${entry.sourceFile || sourceFileForPrompt(entry)}`
}

function assertReadyEntriesBeforePublish(entries) {
  const failures = []
  for (const entry of entries) {
    const route = entry.canonicalPath || entry.route || entry.promptId
    const score = Number(entry.score) || 0
    if (entry.status !== "ready") {
      failures.push(`${route}: status=${entry.status || "(missing)"}`)
    }
    if (score < MIN_SCORE) {
      failures.push(`${route}: score=${score} < ${MIN_SCORE}`)
    }
    if (hasDuplicateHeadingIssue(entry.issues || [])) {
      failures.push(`${route}: duplicate heading issue already present (${entry.issues.join(",")})`)
    }
    let body
    try {
      body = markdownBodyForEntry(entry)
    } catch (err) {
      failures.push(`${route}: ${err.message}`)
      continue
    }
    const duplicateHeadings = duplicateMarkdownHeadingDetails(body)
    if (duplicateHeadings.length) {
      const sample = duplicateHeadings
        .slice(0, 3)
        .map((item) => `${item.first} <=> ${item.duplicate}`)
        .join(" | ")
      failures.push(`${route}: duplicate-heading:${duplicateHeadings.length} ${sample}`)
    }
  }
  if (failures.length) {
    throw new Error(`Refusing to publish articles that fail the strict heading gate: ${failures.slice(0, 8).join("; ")}`)
  }
}

function runSeoReadyFilesCheck(entries) {
  const files = entries.map(sourcePathForEntry).filter(Boolean)
  if (files.length !== entries.length) {
    throw new Error(`Cannot run SEO_READY_FILES check: expected ${entries.length} source files, got ${files.length}`)
  }
  const uniqueFiles = [...new Set(files)]
  console.log(`[CHECK] SEO_READY_FILES=${uniqueFiles.join(",")} node scripts/check-seo-ready-routes.mjs`)
  execFileSync(process.execPath, ["scripts/check-seo-ready-routes.mjs"], {
    cwd: ROOT,
    stdio: "inherit",
    env: {
      ...process.env,
      SEO_READY_FILES: uniqueFiles.join(","),
    },
  })
}

async function publishReadyEntries(entries, publishedState) {
  if (!entries.length) return
  assertReadyEntriesBeforePublish(entries)
  if (DRY_RUN) {
    for (const entry of entries) {
      console.log(`[DRY] slug=${entry.slug} source=${entry.sourcePath} r2_key=${entry.r2Key} score=${entry.score} title=${entry.title}`)
    }
    return
  }

  if (PUBLISH_CONTENT) {
    writeSourceMarkdownEntries(entries)
    runSeoReadyFilesCheck(entries)
  }

  if (UPLOAD_R2) {
    for (const entry of entries) {
      await uploadR2(entry)
    }
  } else {
    for (const entry of entries) {
      console.log(`[D1]   slug=${entry.slug} storing body_html in D1; R2 upload disabled`)
    }
  }
  await upsertD1(entries)

  publishedState.drafts.push(...entries.map((entry) => {
    const publicEntry = { ...entry }
    delete publicEntry.bodyHtml
    delete publicEntry.bodyMarkdown
    return publicEntry
  }))
  saveJsonState(PUBLISHED_FILE, publishedState)
}

function writeSourceMarkdownEntries(entries) {
  mkdirSync(CONTENT_READY_DIR, { recursive: true })
  for (const entry of entries) {
    const file = entry.sourceFile || sourceFileForPrompt(entry)
    const target = join(CONTENT_READY_DIR, file)
    if (existsSync(target) && !ALLOW_SOURCE_OVERWRITE) {
      const meta = parseFrontmatter(readFileSync(target, "utf8"))
      const existingPath = normalizeCanonicalPath(meta.canonicalPath || "")
      if (existingPath !== normalizeCanonicalPath(entry.canonicalPath)) {
        throw new Error(`Refusing to overwrite ${target}; existing canonicalPath=${existingPath}`)
      }
      throw new Error(`Refusing to overwrite existing ready source file: ${target}`)
    }
    writeFileSync(target, markdownForEntry(entry), "utf8")
    console.log(`[MD]   ${entry.canonicalPath} -> content/seo-ready/${file}`)
  }
}

async function main() {
  const bank = loadPromptBank()
  const publishedState = loadJsonState(PUBLISHED_FILE, { drafts: [] })
  const failedState = loadJsonState(FAILED_LOG_FILE, { drafts: [] })
  const history = await loadPromptBankHistory({ root: ROOT, minScore: MIN_SCORE })
  const completedRoutes = loadExistingCanonicalPaths()
  const existingRoutePaths = new Set([...completedRoutes, ...history.canonicalPaths])
  const publishedH1s = loadExistingH1Set()
  void publishedH1s
  const completed = new Set(
    publishedState.drafts
      .filter((d) => d.promptId && d.status === "ready")
      .map((d) => d.promptId),
  )

  const filtered = bank.filter((p) => {
    if (ONLY_LOCALE && p.locale !== ONLY_LOCALE) return false
    return true
  })

  const queue = []
  const skipCounts = new Map()
  for (const prompt of filtered) {
    const reason = skipReasonForPrompt(prompt, history, completed, existingRoutePaths)
    if (reason) {
      skipCounts.set(reason, (skipCounts.get(reason) || 0) + 1)
      console.log(`[SKIP] ${prompt.promptId} ${prompt.route} reason=${reason}`)
      continue
    }
    queue.push(prompt)
  }

  // In bilingual mode, interleave ZH and EN so we don't exhaust one lang first.
  let finalQueue = queue
  if (TARGET_READY_COUNT > 0 && !ONLY_LOCALE && TARGET_READY_COUNT % 2 === 0) {
    const zhQueue = queue.filter((p) => p.locale === "zh")
    const enQueue = queue.filter((p) => p.locale === "en")
    finalQueue = []
    const maxLen = Math.max(zhQueue.length, enQueue.length)
    for (let i = 0; i < maxLen; i++) {
      if (i < zhQueue.length) finalQueue.push(zhQueue[i])
      if (i < enQueue.length) finalQueue.push(enQueue[i])
    }
  }

  console.log(`Prompt bank      : ${PROMPT_BANK_FILE}`)
  console.log(`Published file   : ${PUBLISHED_FILE}`)
  console.log(`D1 database      : ${CLOUDFLARE_D1_DATABASE} (${CLOUDFLARE_D1_DATABASE_ID})`)
  console.log(`R2 bucket        : ${CLOUDFLARE_R2_BUCKET}`)
  console.log(`Dry run          : ${DRY_RUN ? "yes" : "no"}`)
  console.log(`Upload R2        : ${UPLOAD_R2 ? "yes" : "no"}`)
  console.log(`Write Markdown   : ${PUBLISH_CONTENT ? "yes" : "no"}`)
  console.log(`Provider per city: ${ASSIGN_PROVIDER_PER_CITY ? `yes (${STRICT_CITY_PROVIDER ? "strict" : "fallback"})` : "no"}`)
  console.log(`Multi candidates : ${MULTI_AI_CANDIDATES ? "yes" : "no"}`)
  console.log(`Total prompts    : ${bank.length}`)
  console.log(`Already published: ${completed.size}`)
  console.log(`Existing routes  : ${existingRoutePaths.size}`)
  for (const reason of ["already_in_d1", "already_in_markdown", "historical_prompt_hash", "historical_profile_hash"]) {
    if (skipCounts.has(reason)) console.log(`Skipped ${reason}: ${skipCounts.get(reason)}`)
  }
  console.log(`Locale filter    : ${ONLY_LOCALE || "(none)"}`)
  console.log(`To process       : ${finalQueue.length}`)
  finalQueue = finalQueue.map((prompt, index) => ({ ...prompt, providerSlot: index + 1 }))
  const bilingualMode = TARGET_READY_COUNT > 0 && !ONLY_LOCALE && TARGET_READY_COUNT % 2 === 0
  const perLangLimit = bilingualMode ? TARGET_READY_COUNT / 2 : 0

  console.log(`Target ready     : ${TARGET_READY_COUNT > 0 ? TARGET_READY_COUNT : "(all)"}`)
  console.log(`Bilingual mode   : ${bilingualMode ? `yes (${perLangLimit} per lang)` : "no"}`)
  console.log(`Concurrency      : ${CONCURRENCY}`)
  console.log(`Batch size       : ${BATCH_SIZE}`)
  console.log(`Rate delay (ms)  : ${RATE_DELAY_MS}`)
  console.log(`Timeout (ms)     : ${TIMEOUT_MS}`)
  console.log(`CF timeout (ms)  : ${CF_TIMEOUT_MS}`)

  if (queue.length === 0) {
    console.log("Nothing to do. Exiting.")
    return
  }

  if (!DRY_RUN) {
    if (!CLOUDFLARE_API_TOKEN) {
      throw new Error("Missing CLOUDFLARE_API_TOKEN")
    }
    if (!CLOUDFLARE_ACCOUNT_ID) {
      throw new Error("Missing CLOUDFLARE_ACCOUNT_ID")
    }
    if (CLOUDFLARE_D1_DATABASE_ID !== EXPECTED_D1_DATABASE_ID) {
      throw new Error(`CLOUDFLARE_D1_DATABASE_ID must be ${EXPECTED_D1_DATABASE_ID}, got ${CLOUDFLARE_D1_DATABASE_ID}`)
    }
    if (CLOUDFLARE_R2_BUCKET !== EXPECTED_R2_BUCKET) {
      throw new Error(`CLOUDFLARE_R2_BUCKET must be ${EXPECTED_R2_BUCKET}, got ${CLOUDFLARE_R2_BUCKET}`)
    }
    console.log("Checking Cloudflare D1 schema...")
    await ensureCloudflareColumns()
    console.log("Cloudflare D1 schema OK.")
  }

  // Bilingual balance: when TARGET_READY_COUNT is set and no locale filter,
  // enforce exactly half ZH + half EN (e.g. RUN_LIMIT=6 → 3 ZH + 3 EN).
  const readyByLang = { zh: 0, en: 0 }

  let ready = 0
  let failed = 0
  let needsReview = 0
  let readyBuffer = []
  let processedSinceCheckpoint = 0

  for (let offset = 0; offset < finalQueue.length; offset += CONCURRENCY) {
    if (TARGET_READY_COUNT > 0 && ready >= TARGET_READY_COUNT) break
    const chunk = finalQueue.slice(offset, offset + CONCURRENCY).filter((p) => {
      if (!bilingualMode || !perLangLimit) return true
      return (readyByLang[p.locale] || 0) < perLangLimit
    })
    if (!chunk.length) continue
    const results = await Promise.allSettled(chunk.map((p) => runOne(p)))

    for (let i = 0; i < chunk.length; i++) {
      const prompt = chunk[i]
      const settled = results[i]

      if (settled.status === "rejected") {
        failed++
        const entry = failedEntry(prompt, settled.reason)
        failedState.drafts.push(entry)
        console.log(`[FAIL] ${prompt.promptId} ${prompt.route} : ${entry.error.slice(0, 200)}`)
        continue
      }

      const result = settled.value
      const postGenerationReason = skipReasonForPrompt({ ...prompt, canonicalPath: result.canonicalPath }, history, completed, existingRoutePaths)
      if (postGenerationReason) {
        console.log(`[SKIP] ${prompt.promptId} ${result.canonicalPath} reason=${postGenerationReason}`)
        continue
      }
      if (result.status !== "ready") {
        needsReview++
        failedState.drafts.push(reviewEntry(result))
        console.log(`[REVW] ${prompt.promptId} ${prompt.route} via ${result.generation.provider} score=${result.score} issues=${result.issues.join(",")}`)
        continue
      }

      ready++
      const entry = readyEntryFromResult(result)
      readyBuffer.push({ ...entry, bodyHtml: result.bodyHtml, bodyMarkdown: result.body })
      existingRoutePaths.add(normalizeCanonicalPath(entry.canonicalPath))
      history.promptHashes.add(entry.promptHash)
      history.profileHashes.add(entry.profileHash)
      history.routeKeys.add(entry.routeKey || routeKeyFor(entry))
      if (bilingualMode) readyByLang[entry.locale] = (readyByLang[entry.locale] || 0) + 1
      console.log(`[OK]   ${prompt.promptId} ${result.slug} via ${result.generation.provider} (score ${result.score})`)

      if (TARGET_READY_COUNT > 0 && ready >= TARGET_READY_COUNT) {
        break
      }
    }

    processedSinceCheckpoint += chunk.length
    if (readyBuffer.length >= BATCH_SIZE) {
      await publishReadyEntries(readyBuffer, publishedState)
      readyBuffer = []
    }
    if (processedSinceCheckpoint >= BATCH_SIZE) {
      saveJsonState(FAILED_LOG_FILE, failedState)
      processedSinceCheckpoint = 0
    }

    if (RATE_DELAY_MS > 0 && offset + CONCURRENCY < queue.length) {
      await sleep(RATE_DELAY_MS)
    }
  }

  await publishReadyEntries(readyBuffer, publishedState)
  saveJsonState(FAILED_LOG_FILE, failedState)
  if (DRY_RUN) saveJsonState(PUBLISHED_FILE, publishedState)

  console.log("---")
  console.log(`Ready          : ${ready}`)
  console.log(`Needs review   : ${needsReview}`)
  console.log(`Failed         : ${failed}`)
  console.log(`Published file : ${PUBLISHED_FILE}`)
}

main().catch((err) => {
  console.error("Fatal:", err)
  process.exit(1)
})
