function mergeIssues(issues = [], extraIssues = []) {
  const out = [...issues]
  for (const issue of extraIssues) {
    const issueKey = issue.split(":")[0]
    if (!out.some((existing) => existing === issue || existing.split(":")[0] === issueKey)) {
      out.push(issue)
    }
  }
  return out
}

