function mergeSupplementalCities(cities) {
  const seen = new Set(cities.map((city) => city.slug))
  const bySlug = new Map(cities.map((city) => [city.slug, city]))
  const merged = cities.slice()
  const supplemental = [
    ...SUPPLEMENTAL_MAINLAND_CITIES.map(([slug, name, nameEn, province, provinceEn]) => [slug, name, nameEn, province, provinceEn, "中国", "China", "CN"]),
    ...SUPPLEMENTAL_MAINLAND_CITIES_EXTRA.map(([slug, name, nameEn, province, provinceEn]) => [slug, name, nameEn, province, provinceEn, "中国", "China", "CN"]),
    ...TOP_WORLD_CITIES_EN.map(([slug, name, nameEn, provinceEn, countryEn, countryCode], index) => [slug, name, nameEn, provinceEn, provinceEn, name, countryEn, countryCode, index + 1]),
  ]
  for (const [slug, name, nameEn, province, provinceEn, country, countryEn, countryCode, enRank] of supplemental) {
    if (seen.has(slug)) {
      const existing = bySlug.get(slug)
      if (existing && enRank && !existing.enRank) existing.enRank = enRank
      if (existing && countryCode && !existing.countryCode) existing.countryCode = countryCode
      if (existing && country && !existing.country) existing.country = country
      if (existing && countryEn && !existing.countryEn) existing.countryEn = countryEn
      continue
    }
    seen.add(slug)
    const city = {
      slug,
      name,
      nameEn,
      province,
      provinceEn,
      country,
      countryEn,
      countryCode,
      ...(enRank ? { enRank } : {}),
    }
    bySlug.set(slug, city)
    merged.push(city)
  }
  return merged
}

function mergeSupplementalTopics(categories) {
  const seen = new Set(categories.map((category) => category.slug))
  const merged = categories.slice()
  for (const [slug, name, nameEn] of SUPPLEMENTAL_TOPICS) {
    if (seen.has(slug)) continue
    seen.add(slug)
    merged.push({ slug, name, nameEn })
  }
  return merged
}

function buildEntries(cities, categories) {
  const entries = []
  for (const city of cities) {
    // ZH city overview
    entries.push({
      locale: "zh",
      citySlug: city.slug,
      cityNameLocalized: city.name,
      countryCode: city.countryCode || "CN",
      country: city.country || "中国",
      countryEn: city.countryEn || "China",
      topicSlug: CITY_OVERVIEW_TOPIC_ZH.slug,
      topicNameLocalized: CITY_OVERVIEW_TOPIC_ZH.name,
      route: `/city/${city.slug}`,
      enabled: true,
    })
    // EN city overview
    entries.push({
      locale: "en",
      citySlug: city.slug,
      cityNameLocalized: city.nameEn,
      countryCode: city.countryCode || "CN",
      country: city.country || "中国",
      countryEn: city.countryEn || "China",
      ...(city.enRank ? { enRank: city.enRank } : {}),
      topicSlug: CITY_OVERVIEW_TOPIC_ZH.slug,
      topicNameLocalized: CITY_OVERVIEW_TOPIC_ZH.nameEn,
      route: `/en/city/${city.slug}`,
      enabled: true,
    })
    for (const cat of categories) {
      entries.push({
        locale: "zh",
        citySlug: city.slug,
        cityNameLocalized: city.name,
        countryCode: city.countryCode || "CN",
        country: city.country || "中国",
        countryEn: city.countryEn || "China",
        topicSlug: cat.slug,
        topicNameLocalized: cat.name,
        route: `/city/${city.slug}/${cat.slug}`,
        enabled: true,
      })
      entries.push({
        locale: "en",
        citySlug: city.slug,
        cityNameLocalized: city.nameEn,
        countryCode: city.countryCode || "CN",
        country: city.country || "中国",
        countryEn: city.countryEn || "China",
        ...(city.enRank ? { enRank: city.enRank } : {}),
        topicSlug: cat.slug,
        topicNameLocalized: cat.nameEn,
        route: `/en/city/${city.slug}/${cat.slug}`,
        enabled: true,
      })
    }
  }
  return entries
}

function main() {
  const cities = mergeSupplementalCities(loadCities())
  const categories = mergeSupplementalTopics(loadCategories())
  const entries = buildEntries(cities, categories)

  // Stable sort: locale, then route
  entries.sort((a, b) => {
    if (a.locale !== b.locale) return a.locale.localeCompare(b.locale)
    return a.route.localeCompare(b.route)
  })

  const enCount = entries.filter((e) => e.locale === "en").length
  const zhCount = entries.filter((e) => e.locale === "zh").length

  const payload = {
    generatedAt: new Date().toISOString(),
    sourceOfTruth: "lib/seo-data.ts",
    counts: {
      total: entries.length,
      en: enCount,
      zh: zhCount,
      cities: cities.length,
      topics: categories.length + 1, // +1 for synthetic city-overview
    },
    entries,
  }

  mkdirSync(dirname(OUT_FILE), { recursive: true })
  writeFileSync(OUT_FILE, JSON.stringify(payload, null, 2) + "\n", "utf8")

  console.log("Route manifest written:", OUT_FILE)
  console.log("  total:", entries.length)
  console.log("  en:   ", enCount)
  console.log("  zh:   ", zhCount)
  console.log("  cities:", cities.length)
  console.log("  topics:", categories.length + 1)
}

main()
